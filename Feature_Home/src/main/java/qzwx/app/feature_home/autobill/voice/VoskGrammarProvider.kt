package qzwx.app.feature_home.autobill.voice

import org.json.JSONArray

/**
 * 自动记账场景语法约束：
 * - 保留日期/时间/金额/收支/钱包/常见分类词
 * - 追加 [unk]，避免过度约束导致漏识别
 */
object VoskGrammarProvider {

    private val grammarTerms = listOf(
        "零", "一", "二", "两", "三", "四", "五", "六", "七", "八", "九", "十", "百", "千", "万", "亿", "点",
        "今天", "明天", "后天", "昨天", "前天", "上午", "中午", "下午", "晚上", "凌晨", "早上", "号", "日", "月", "年",
        "点", "分", "半", "一刻", "三刻",
        "元", "块", "毛", "角", "分", "人民币",
        "收入", "支出", "花了", "用了", "支付", "付款", "消费", "报销", "转账", "转入", "转出", "工资", "兼职",
        "微信", "支付宝", "现金", "银行卡", "云闪付", "花呗", "信用卡",
        "吃饭", "餐饮", "交通", "购物", "买菜", "打车", "地铁", "公交", "房租", "电影", "医疗", "学习", "充值",
        "[unk]"
    )

    fun buildAutoBillGrammarJson(): String {
        return JSONArray(grammarTerms).toString()
    }
}

